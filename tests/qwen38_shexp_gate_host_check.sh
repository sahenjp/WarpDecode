#!/usr/bin/env bash
# Host bit-comparison of the F32 weight x F32 activation dots in
# src/qwen38_moe.cuh, src/matrix.cuh and src/qwen38_hc.cuh against the real
# llama.cpp CPU ggml_vec_dot_f32() at the pinned oracle commit
# (6fcaa16f4b360649933a54d1f91ad40ed35c0e11).
#
# The oracle evaluates every F32 projection with vec_dot_type == F32 and
# nrows == 1, and llamafile_sgemm() declines a single decode token, so each row
# is one vec_dot(ne00, ..., nrc == 1) == ggml_vec_dot_f32:
#
#   * build_lora_mm(blk.N.ffn_gate_inp_shexp.weight, cur)  shared expert gate
#   * build_lora_mm(blk.N.ffn_gate_inp.weight, cur)        MoE router
#   * build_lora_mm(blk.N.hc_*_inject.weight, xn)          HC inject
#
# The candidates are the extracted source text of the three AVX2-order kernels,
# so the host check cannot pass against a stale copy.
#
# The checkout must be built the same way as the CPU oracle:
#
#   LLAMA=/tmp/qwen38-pinned-llama
#   git clone https://github.com/ggml-org/llama.cpp "$LLAMA"
#   git -C "$LLAMA" checkout 6fcaa16f4b360649933a54d1f91ad40ed35c0e11
#   cmake -S "$LLAMA" -B "$LLAMA/build-host" -DCMAKE_BUILD_TYPE=Release \
#     -DGGML_NATIVE=OFF -DGGML_CUDA=OFF -DGGML_BUILD_TESTS=OFF \
#     -DGGML_BUILD_EXAMPLES=OFF -DLLAMA_BUILD_TESTS=OFF \
#     -DLLAMA_BUILD_EXAMPLES=OFF -DLLAMA_BUILD_TOOLS=OFF -DLLAMA_BUILD_SERVER=OFF
#   cmake --build "$LLAMA/build-host" --target ggml-cpu ggml-base -j"$(nproc)"
#
# Usage: bash tests/qwen38_shexp_gate_host_check.sh [llama.cpp checkout] [n_random]
set -euo pipefail

ROOT=$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)
LLAMA=${1:-${LLAMA_CPP:-}}
PER_GROUP=${2:-200}

if [[ -z "$LLAMA" || ! -f "$LLAMA/ggml/src/ggml-cpu/vec.h" ]]; then
  echo "usage: bash tests/qwen38_shexp_gate_host_check.sh <llama.cpp checkout> [n_random]" >&2
  echo "       (or export LLAMA_CPP=...)" >&2
  exit 2
fi
if [[ ! -f "$LLAMA/build-host/bin/libggml-cpu.so" ]]; then
  echo "missing $LLAMA/build-host/bin/libggml-cpu.so - see the header of this script" >&2
  exit 2
fi

WORK=${Q38_SHEXP_GATE_WORK:-/tmp/qwen38-shexp-gate-host}
mkdir -p "$WORK"

# ---------------------------------------------------------------------------
# Static confirmations: the ops the kernels reproduce are the ones the CPU
# oracle dispatches for this model, and the AVX2 macro set is the one the oracle
# image was compiled with.
# ---------------------------------------------------------------------------
grep -q 'layer.ffn_gate_inp_shexp = create_tensor(tn(LLM_TENSOR_FFN_GATE_INP_SHEXP, "weight", il), { n_embd }, flags);' "$LLAMA/src/models/qwen4exp.cpp"
grep -q 'layer.ffn_gate_inp  = create_tensor(tn(LLM_TENSOR_FFN_GATE_INP,  "weight", il), { n_embd, n_expert }, flags);' "$LLAMA/src/models/qwen4exp.cpp"
grep -q 'ggml_tensor \* shared_gate = build_lora_mm(model.layers\[il\].ffn_gate_inp_shexp, cur);' "$LLAMA/src/models/qwen4exp.cpp"
grep -q 'shared_gate = ggml_sigmoid(ctx0, shared_gate);' "$LLAMA/src/models/qwen4exp.cpp"
grep -q '\*inject = build_lora_mm(w_inject, xn);' "$LLAMA/src/models/qwen4exp.cpp"
grep -q '.vec_dot_type             = GGML_TYPE_F32,' "$LLAMA/ggml/src/ggml-cpu/ggml-cpu.c"
grep -q '.nrows                    = 1,' "$LLAMA/ggml/src/ggml-cpu/ggml-cpu.c"
grep -q 'if (n < 2)' "$LLAMA/ggml/src/ggml-cpu/llamafile/sgemm.cpp"
grep -q 'vec_dot(ne00, &tmp\[ir0 - iir0\]' "$LLAMA/ggml/src/ggml-cpu/ggml-cpu.c"
grep -q '#define GGML_F32_STEP 32' "$LLAMA/ggml/src/ggml-cpu/simd-mappings.h"
grep -q '#define GGML_F32_EPR  8' "$LLAMA/ggml/src/ggml-cpu/simd-mappings.h"
grep -q 'sumf += x\[i\]\*y\[i\];' "$LLAMA/ggml/src/ggml-cpu/vec.cpp"

# ---------------------------------------------------------------------------
# Drift guard: each candidate is the real source text of its kernel.
# ---------------------------------------------------------------------------
extract_region() {
  local file="$1" start_pat="$2" kernel_pat="$3" out="$4"
  local start kstart end
  start=$(grep -n "$start_pat" "$file" | head -1 | cut -d: -f1)
  kstart=$(grep -n "$kernel_pat" "$file" | head -1 | cut -d: -f1)
  if [[ -z "$start" || -z "$kstart" ]]; then
    echo "failed to locate $kernel_pat in $file" >&2
    exit 2
  fi
  end=$(awk -v s="$kstart" 'NR >= s && /^\}$/ { print NR; exit }' "$file")
  if [[ -z "$end" || "$end" -le "$kstart" ]]; then
    echo "failed to find the end of $kernel_pat in $file" >&2
    exit 2
  fi
  sed -n "${start},${end}p" "$file" >> "$out"
}

EXTRACT="$WORK/qwen38_shexp_gate_extract.h"
{
  echo '// Generated by tests/qwen38_shexp_gate_host_check.sh - do not edit.'
} > "$EXTRACT"
extract_region "$ROOT/src/qwen38_moe.cuh"   '^__device__ __forceinline__ float q38_moe_reduce_avx2('   '^__global__ void q38_moe_gate_dot_f32_avx2_kernel(' "$EXTRACT"
extract_region "$ROOT/src/matrix.cuh"   '^__device__ __forceinline__ float q38_matrix_reduce_avx2('   '^__global__ void dense_f32_gemv_avx2_kernel(' "$EXTRACT"
extract_region "$ROOT/src/qwen38_hc.cuh"   '^__device__ __forceinline__ float q38_hc_reduce_avx2('   '^__global__ void q38_hc_dense_gemv_f32_avx2_kernel(' "$EXTRACT"

for needle in \
  'sum\[j\]\[l\] = __fmaf_rn(w\[c\], x\[c\], sum\[j\]\[l\]);' \
  'sum\[j\]\[l\] = __fmaf_rn(row_ptr\[c\], x\[c\], sum\[j\]\[l\]);' \
  'float acc = q38_moe_reduce_avx2(sum);' \
  'float acc = q38_matrix_reduce_avx2(sum);' \
  'float acc = q38_hc_reduce_avx2(sum);' \
  'acc = __fadd_rn(acc, __fmul_rn(w\[c\], x\[c\]));' \
  'acc = __fadd_rn(acc, __fmul_rn(row_ptr\[c\], x\[c\]));'; do
  if ! grep -q "$needle" "$EXTRACT"; then
    echo "extracted section is missing: $needle" >&2
    exit 2
  fi
done

# ---------------------------------------------------------------------------
# The extracted text is compiled as plain host code: the CUDA qualifiers become
# no-ops and the rounding-mode intrinsics map onto their exactly-rounded host
# twins. -ffp-contract=off keeps every "+" and "*" a single IEEE operation, so
# the accidentals match the device kernel and the oracle's GCC build.
# ---------------------------------------------------------------------------
g++ -std=c++17 -O2 -ffp-contract=off -mavx -mavx2 -mfma -mf16c -msse4.2 -mbmi2 \
  -Wall -Wextra -Wno-unknown-pragmas -Wno-unused-function \
  -D__global__=static -D__device__= -D__forceinline__=inline \
  -D__restrict__= -D__restrict= \
  -D'__fmaf_rn(a,b,c)=__builtin_fmaf(a,b,c)' \
  -D'__fadd_rn(a,b)=((a)+(b))' \
  -D'__fmul_rn(a,b)=((a)*(b))' \
  -I "$WORK" -I "$ROOT/src" \
  -I "$LLAMA/ggml/include" -I "$LLAMA/ggml/src" -I "$LLAMA/ggml/src/ggml-cpu" \
  "$ROOT/tests/qwen38_shexp_gate_host_test.cpp" \
  -L "$LLAMA/build-host/bin" -lggml-cpu -lggml-base -Wl,-rpath,"$LLAMA/build-host/bin" \
  -o "$WORK/shexp_gate_host_test"

"$WORK/shexp_gate_host_test" "$PER_GROUP"

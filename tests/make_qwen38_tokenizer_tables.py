#!/usr/bin/env python3
"""Generate src/qwen38_tokenizer_unicode.inc from a llama.cpp checkout.

The tokenizer port in src/qwen38_tokenizer.cuh must classify codepoints exactly
like llama.cpp's unicode_cpt_flags / unicode_tolower, otherwise the Qwen2 /
Qwen3.5 pre-tokenization split points differ and the token IDs diverge. Rather
than re-deriving the Unicode tables (and risking a different UCD vintage), this
script reads them from the pinned llama.cpp source:

  src/unicode-data.cpp   unicode_ranges_flags / unicode_set_whitespace /
                         unicode_map_lowercase / unicode_map_uppercase /
                         unicode_ranges_nfd

and writes the same information as compact C++ arrays. The generator is part of
tests/ so the tables can be regenerated against any llama.cpp revision:

  python3 tests/make_qwen38_tokenizer_tables.py /path/to/llama.cpp
  bash tests/qwen38_tokenizer_host_check.sh /path/to/llama.cpp   # regenerates + verifies
"""
from __future__ import annotations

import argparse
import pathlib
import re
import subprocess
import sys

UNDEFINED = 0x0001
NUMBER = 0x0002
LETTER = 0x0004
SEPARATOR = 0x0008
ACCENT_MARK = 0x0010
PUNCTUATION = 0x0020
SYMBOL = 0x0040
CONTROL = 0x0080
WHITESPACE = 0x0100
LOWERCASE = 0x0200
UPPERCASE = 0x0400
NFD = 0x0800
MAX_CODEPOINTS = 0x110000
ENTRY = re.compile(r"\{\s*(0x[0-9A-Fa-f]+)\s*,\s*(0x[0-9A-Fa-f]+)\s*\}")
TRIPLE = re.compile(r"\{\s*(0x[0-9A-Fa-f]+)\s*,\s*(0x[0-9A-Fa-f]+)\s*,\s*(0x[0-9A-Fa-f]+)\s*\}")
BARE = re.compile(r"^(0x[0-9A-Fa-f]+),", re.M)


def section(text: str, header: str) -> str:
    start = text.index(header)
    end = text.index("};", start)
    return text[start:end]


def pairs(body: str) -> list[tuple[int, int]]:
    return [(int(a, 16), int(b, 16)) for a, b in ENTRY.findall(body)]


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("llama_cpp", help="llama.cpp checkout (uses src/unicode-data.cpp)")
    parser.add_argument("--out", default="src/qwen38_tokenizer_unicode.inc")
    args = parser.parse_args()

    root = pathlib.Path(args.llama_cpp).resolve()
    data_path = root / "src/unicode-data.cpp"
    text = data_path.read_text(encoding="utf-8")

    ranges_flags = pairs(section(text, "unicode_ranges_flags = {"))
    whitespace = [int(cp, 16) for cp in BARE.findall(section(text, "unicode_set_whitespace = {"))]
    lowercase = pairs(section(text, "unicode_map_lowercase = {"))
    uppercase = pairs(section(text, "unicode_map_uppercase = {"))
    nfd_ranges = [(int(a, 16), int(b, 16), int(c, 16))
                  for a, b, c in TRIPLE.findall(section(text, "unicode_ranges_nfd = {"))]

    flags = [UNDEFINED] * MAX_CODEPOINTS
    for i in range(1, len(ranges_flags)):
        ini, value = ranges_flags[i - 1]
        end = ranges_flags[i][0]
        for cp in range(ini, end):
            flags[cp] = value
    for cp in whitespace:
        flags[cp] |= WHITESPACE
    for _, lo in lowercase:
        flags[lo] |= LOWERCASE
    for _, up in uppercase:
        flags[up] |= UPPERCASE
    for first, last, target in nfd_ranges:
        flags[target] |= NFD

    merged: list[tuple[int, int, int]] = []
    run_start = 0
    for cp in range(1, MAX_CODEPOINTS):
        if flags[cp] != flags[run_start]:
            merged.append((run_start, cp, flags[run_start]))
            run_start = cp
    merged.append((run_start, MAX_CODEPOINTS, flags[run_start]))

    try:
        commit = subprocess.run(["git", "-C", str(root), "rev-parse", "HEAD"],
                                capture_output=True, text=True, check=True).stdout.strip()
    except Exception:
        commit = "unknown"

    lines: list[str] = []
    lines.append("// Generated by tests/make_qwen38_tokenizer_tables.py -- do not edit.")
    lines.append("// Source: llama.cpp %s (src/unicode-data.cpp via src/unicode.cpp rules)." % commit)
    lines.append("// Codepoint flags are llama.cpp's unicode_cpt_flags bit layout:")
    lines.append("//   0x0001 UNDEFINED 0x0002 NUMBER 0x0004 LETTER 0x0008 SEPARATOR")
    lines.append("//   0x0010 ACCENT_MARK 0x0020 PUNCTUATION 0x0040 SYMBOL 0x0080 CONTROL")
    lines.append("//   0x0100 WHITESPACE 0x0200 LOWERCASE 0x0400 UPPERCASE 0x0800 NFD")
    lines.append("// Ranges are [first, last) and sorted; flags range over the whole 0..0x10FFFF space.")
    lines.append("static const Qwen38UnicodeRange kQwen38UnicodeFlags[] = {")
    for first, last, value in merged:
        lines.append("{0x%06X, 0x%06X, 0x%04X}," % (first, last, value))
    lines.append("};")
    lines.append("")
    lines.append("// llama.cpp unicode_tolower() (src/unicode.cpp), sorted by codepoint.")
    lines.append("static const Qwen38CasePair kQwen38Lowercase[] = {")
    for src, dst in lowercase:
        lines.append("{0x%06X, 0x%06X}," % (src, dst))
    lines.append("};")

    out_path = pathlib.Path(args.out)
    if not out_path.is_absolute():
        out_path = pathlib.Path(__file__).resolve().parents[1] / args.out
    out_path.write_text("\n".join(lines) + "\n", encoding="utf-8")

    wide = [item for item in lowercase if item[1] < 128 and item[0] >= 128]
    print("wrote %s" % out_path)
    print("  source=%s commit=%s" % (data_path, commit))
    print("  ranges=%d (from %d flag entries) lowercase=%d nfd=%d"
          % (len(merged), len(ranges_flags), len(lowercase), len(nfd_ranges)))
    print("  non-ASCII codepoints lowercasing into ASCII: %s" % (wide or "none"))
    return 0


if __name__ == "__main__":
    sys.exit(main())
